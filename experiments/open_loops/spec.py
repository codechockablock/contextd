def build_spec() -> dict:
    spec = json.loads(json.dumps(SPEC))
    spec["fixture_digest"] = fixture_digest()
    split = split_fixtures()
    spec["split"] = {
        "calibration": [f["fid"] for f in split["calibration"]],
        "heldout": [f["fid"] for f in split["heldout"]],
    }
    n_plants = sum(1 for f in split["heldout"] for p in f["planted"]
                   if p["label"] == "must_capture")
    n_dialogues = sum(1 for f in split["heldout"]
                      if f["shape"] != "identical_pair")
    if n_plants != spec["endpoints"]["capture"]["n"]:
        raise RuntimeError(f"spec n mismatch: {n_plants} held-out plants")
    if n_dialogues != spec["endpoints"]["confirmation_burden"]["n_dialogues"]:
        raise RuntimeError(f"spec n mismatch: {n_dialogues} held-out dialogues")
    return spec


def spec_sha() -> str:
    return hashlib.sha256(
        json.dumps(build_spec(), sort_keys=True).encode()).hexdigest()


